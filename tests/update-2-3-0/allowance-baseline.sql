-- Local PostgreSQL compatibility fixture for Update 2.3.0 allowance migration.
-- This is intentionally a minimal Supabase-like schema, not a copy of production data.
-- It runs only in the disposable PostgreSQL service created by GitHub Actions.

create role anon nologin;
create role authenticated nologin;

create schema auth;
create schema private;

create function auth.uid()
returns uuid
language sql
stable
as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

grant usage on schema auth, public, private to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;

create table public.user_preferences (
  user_id uuid primary key,
  timezone text not null default 'UTC'
);

create table public.user_entitlements (
  user_id uuid primary key,
  plan_code text not null,
  status text not null,
  valid_from timestamptz,
  valid_until timestamptz
);

create table public.learning_plan_limits (
  plan_code text not null,
  activity_type text not null,
  daily_limit integer not null,
  is_enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint learning_plan_limits_activity_type_check
    check (activity_type in ('lesson', 'quiz', 'flashcard')),
  primary key (plan_code, activity_type)
);

create table public.learning_activity_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  activity_type text not null,
  language_code text not null default 'en',
  created_at timestamptz not null default now(),
  constraint learning_activity_log_activity_type_check
    check (activity_type in ('lesson', 'quiz', 'flashcard'))
);

create table public.lesson_progress (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  difficulty text not null,
  lesson_id text not null,
  status text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint lesson_progress_status_check
    check (status in ('in_progress', 'completed')),
  constraint lesson_progress_unique_user_lesson
    unique (user_id, difficulty, lesson_id)
);

create or replace function private.is_learning_limit_exempt()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() = '22222222-2222-4222-8222-222222222222'::uuid
$$;

create or replace function public.enforce_learning_daily_limit()
returns trigger
language plpgsql
as $$
begin
  new.created_at := now();
  return new;
end;
$$;

create trigger enforce_learning_daily_limit
before insert on public.learning_activity_log
for each row execute function public.enforce_learning_daily_limit();

create or replace function public.record_lesson_start_allowance()
returns trigger
language plpgsql
as $$
begin
  insert into public.learning_activity_log(user_id, activity_type, language_code)
  values (new.user_id, 'lesson', 'en');
  return new;
end;
$$;

create trigger lesson_progress_charge_on_first_start
after insert on public.lesson_progress
for each row execute function public.record_lesson_start_allowance();

create or replace function public.guard_lesson_progress_update()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'in_progress' then
    new.completed_at := null;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger guard_lesson_progress_update
before update on public.lesson_progress
for each row execute function public.guard_lesson_progress_update();

alter table public.lesson_progress enable row level security;
alter table public.learning_activity_log enable row level security;
alter table public.user_preferences enable row level security;
alter table public.user_entitlements enable row level security;
alter table public.learning_plan_limits enable row level security;

create policy "Users can read their own lessons"
on public.lesson_progress for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can start their own lessons"
on public.lesson_progress for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can update their own lessons"
on public.lesson_progress for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users can read their own learning activity"
on public.learning_activity_log for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can record their own learning activity"
on public.learning_activity_log for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can read their own preferences"
on public.user_preferences for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can read their own entitlements"
on public.user_entitlements for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Learning limits are readable"
on public.learning_plan_limits for select to authenticated
using (true);

grant select, insert, update on public.lesson_progress to authenticated;
grant select, insert on public.learning_activity_log to authenticated;
grant select on public.user_preferences, public.user_entitlements,
  public.learning_plan_limits to authenticated;
grant usage, select on sequence public.learning_activity_log_id_seq to authenticated;

