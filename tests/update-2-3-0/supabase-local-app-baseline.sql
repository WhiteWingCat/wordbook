create table public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  learning_language text not null default 'en' references public.languages(code),
  translation_language text not null default 'zh' references public.languages(code),
  timezone text not null default 'UTC',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_code text not null default 'free' check (plan_code in ('free','premium')),
  status text not null default 'active' check (status in ('active','inactive','expired','suspended')),
  valid_from timestamptz,
  valid_until timestamptz,
  source text not null default 'default' check (source in ('default','admin','promotion','payment_provider')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_entitlements_validity_order check (valid_until is null or valid_from is null or valid_until > valid_from)
);

create table public.learning_plan_limits (
  plan_code text not null check (plan_code in ('free','premium')),
  activity_type text not null,
  daily_limit integer not null check (daily_limit >= 0),
  is_enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint learning_plan_limits_activity_type_check
    check (activity_type in ('lesson', 'quiz', 'flashcard')),
  primary key (plan_code, activity_type)
);

create table public.learning_activity_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_type text not null,
  language_code text not null default 'en' references public.languages(code),
  created_at timestamptz not null default now(),
  constraint learning_activity_log_activity_type_check
    check (activity_type in ('lesson', 'quiz', 'flashcard'))
);

create table public.lesson_practice_results (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  difficulty text not null check (difficulty in ('beginner','intermediate','advanced')),
  lesson_id text not null check (char_length(lesson_id) between 1 and 120),
  topic_id text not null check (char_length(topic_id) between 1 and 120),
  correct_count integer not null check (correct_count >= 0),
  question_count integer not null,
  attempted_at timestamptz not null default now(),
  constraint lesson_practice_results_check
    check (question_count > 0 and correct_count <= question_count)
);

create table public.lesson_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  difficulty text not null check (difficulty in ('beginner','intermediate','advanced')),
  lesson_id text not null check (char_length(lesson_id) between 1 and 120),
  status text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint lesson_progress_status_check
    check (status in ('in_progress', 'completed')),
  constraint lesson_progress_completion_consistent
    check ((status = 'in_progress' and completed_at is null) or (status = 'completed' and completed_at is not null)),
  constraint lesson_progress_unique_user_lesson
    unique (user_id, difficulty, lesson_id)
);

